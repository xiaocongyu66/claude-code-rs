/// 加密随机整数，范围 [0, max)。
///
/// crypto.randomBytes + 拒绝采样：剔除取模偏差区间
///（CodeQL js/biased-cryptographic-random）。Rust 端取 uuid v4 的
/// 前 4 字节作为随机源。
fn random_int(max: u32) -> u32 {
    debug_assert!(max > 0);
    // 2^32 / max * max —— 剔除会使取模有偏的区间（与 TS 同一公式，
    // 用 u64 运算以保留 max 整除 2^32 时 limit = 2^32 的边界行为）
    let max = max as u64;
    let limit = (0x1_0000_0000u64 / max) * max;
    loop {
        let uuid = Uuid::new_v4();
        let value = u32::from_be_bytes([
            uuid.as_bytes()[0],
            uuid.as_bytes()[1],
            uuid.as_bytes()[2],
            uuid.as_bytes()[3],
        ]) as u64;
        if value < limit {
            return (value % max) as u32;
        }
    }
}

fn pick_random(array: &[&str]) -> &str {
    array[random_int(array.len() as u32) as usize]
}

/// 生成 "adjective-verb-noun" 形态的随机词组 slug。
/// 示例："gleaming-brewing-phoenix"、"cosmic-pondering-lighthouse"
pub fn generate_word_slug() -> String {
    format!(
        "{}-{}-{}",
        pick_random(ADJECTIVES),
        pick_random(VERBS),
        pick_random(NOUNS)
    )
}

/// 生成较短的 "adjective-noun" slugged。
/// 示例："graceful-unicorn"、"cosmic-lighthouse"
pub fn generate_short_word_slug() -> String {
    format!("{}-{}", pick_random(ADJECTIVES), pick_random(NOUNS))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn slug_shapes() {
        let slug = generate_word_slug();
        let parts: Vec<&str> = slug.split('-').collect();
        assert_eq!(parts.len(), 3);
        assert!(parts.iter().all(|p| !p.is_empty()));

        let short = generate_short_word_slug();
        let parts: Vec<&str> = short.split('-').collect();
        assert_eq!(parts.len(), 2);
    }

    #[test]
    fn slugs_are_random_and_from_the_tables() {
        let a = generate_word_slug();
        let b = generate_word_slug();
        assert_ne!(a, b);
        for part in a.split('-') {
            let in_table =
                ADJECTIVES.contains(&part) || VERBS.contains(&part) || NOUNS.contains(&part);
            assert!(in_table, "unknown word: {part}");
        }
    }
}
